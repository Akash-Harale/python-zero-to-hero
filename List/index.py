# Python
arr = [1, 2, 3, 4, 5]
arr.append(6)          # push = append
arr.pop()              # same
len(arr)               # .length = len()
[x * 2 for x in arr]  # map = list comprehension
[x for x in arr if x > 2]   # filter
3 in arr               # includes = in
arr[1:3]               # slice = slicing